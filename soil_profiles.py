PROFILE_TITLES = {key: value["title"] for key, value in PROFILES.items()}


def sample_soil(state, profile_key):
    """Возвращает набор показателей. state — словарь текущих значений датчика (меняется между вызовами)."""
    ranges = PROFILES[profile_key]["ranges"]
    values = {}
    for key, (lo, hi) in ranges.items():
        current = state.get(key, (lo + hi) / 2)
        step = (hi - lo) * 0.04
        current = min(hi, max(lo, current + random.uniform(-step, step)))
        state[key] = current
        digits = 2 if key in ("salinity", "ph") else (0 if key in ("water", "n", "p", "k") else 1)
        values[key] = round(current, digits)
    values["water"] = int(values["water"])
    return values
